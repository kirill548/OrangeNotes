"""Independent adversarial checks for extractive note title safety."""
import unittest

from app.services.note_titles import suggest_note_title


CASES = (
    ('мне надо сходить в магазин', 'Поход в магазин'),
    ('мне нужно к врачу, но визит отменён', 'к врачу, но визит отменён'),
    ('мне нужно к врачу не идти', 'к врачу не идти'),
    ('к врачу позвонить, а не идти', 'к врачу позвонить, а не идти'),
    ('приём к врачу перенесён на завтра', 'приём к врачу перенесён на завтра'),
    ('отменить визит к врачу завтра', 'отменить визит к врачу завтра'),
    ('оплатить счёт 15.10', 'оплатить счёт 15.10'),
    ('проверить версию 3.14 библиотеки', 'проверить версию 3.14 библиотеки'),
    ('проверить ID 15.10.2026', 'проверить ID 15.10.2026'),
    ('отправить отчёт за 15 октября', 'отправить отчёт за 15 октября'),
    ('купить билет на завтра', 'купить билет на завтра'),
    ('завтра не идти к врачу', 'завтра не идти к врачу'),
    ('мне надо забрать справку от врача', 'забрать справку от врача'),
    ('встретиться с Иваном, обсудить договор', 'Встреча с Иваном, обсудить договор'),
    ('мне нужно записаться к врачу на 15 октября', 'записаться к врачу на 15 октября'),
    ('сегодня важная дата: 15 октября 1815', 'сегодня важная дата: 15 октября 1815'),
    ('не отменять запись к врачу', 'не отменять запись к врачу'),
    ('у меня приём у врача в 15:00', 'приём у врача'),
    ('проверить пароль 12:00', 'проверить пароль 12:00'),
    ('необходимо НЕ отправлять отчёт', 'НЕ отправлять отчёт'),
)


class NoteTitleSafetyTests(unittest.TestCase):
    """Every input has a separate discoverable test and a precise safe title."""


def _case_test(body, expected):
    def test(self):
        self.assertEqual(suggest_note_title(body), expected)
    return test


for _index, (_body, _expected) in enumerate(CASES, 1):
    setattr(NoteTitleSafetyTests, f'test_adversarial_{_index:02d}', _case_test(_body, _expected))


if __name__ == '__main__':
    unittest.main()
